# fsig8(t) from GR/wCDM model:
def contrast_wCDM(t, y, O_m0, w):
  D_wCDM = y[0]
  dD_wCDM = y[1]
  O_m = O_m0*t**(-3)
  O_r = O_r0*t**(-4)
  O_L0 = 1 - O_m0
  O_L = O_L0*t**(-3*(1 + w))
  E_wCDM = np.sqrt(O_m + O_r + O_L)
  dE_wCDM = - (E_wCDM/t) - (0.5/t)*(1/E_wCDM)*(O_m + 2*O_r - 2*O_L)
  ddD_wCDM = - ((3/t) + (dE_wCDM/E_wCDM))*dD_wCDM + (3/(2*t**2*E_wCDM**2))*O_m*D_wCDM
  return [dD_wCDM, ddD_wCDM]

def D_wCDM(O_m0, w):
  y0 = [0.2, 1]
  sol_wCDM = solve_ivp(contrast_wCDM, t_span, y0, t_eval=t, method='LSODA', args=(O_m0,w))
  D_wCDM = sol_wCDM.y[0]
  return D_wCDM

def fs8_wCDM(arsd, O_m0, w, sig80):
  y0 = [0.2, 1]
  sol_wCDM = solve_ivp(contrast_wCDM, t_span, y0, t_eval=arsd, method='LSODA', args=(O_m0,w))
  dD_wCDM = sol_wCDM.y[1]
  fs8_wCDM = sig80*arsd*(dD_wCDM/D_wCDM(O_m0,w)[999])
  return fs8_wCDM

