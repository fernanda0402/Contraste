# H(t) from GR/wCDM model:
def Hubble_wCDM(acc, H0, O_m0, w):
  O_m = O_m0*acc**(-3)
  O_r = O_r0*acc**(-4)
  O_L0 = 1 - O_m0
  O_L = O_L0*acc**(-3*(1 + w))
  H_wCDM = H0*np.sqrt(O_m + O_r + O_L)
  return H_wCDM

