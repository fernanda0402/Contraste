# --------------- chi2 SNe --------------- #
def delta(a_sn, H0, O_m0, w, Mb, y_sn):
  mb_model = mag_wCDM(a_sn, H0, O_m0, w, Mb)
  delta = y_sn - mb_model
  return delta

def chi2_SN(a_sn, H0, O_m0, w, Mb, y_sn, Icov):
  chisq = np.sum(np.dot(np.dot(delta(a_sn, H0, O_m0, w, Mb, y_sn), Icov), delta(a_sn, H0, O_m0, w, Mb, y_sn)))
  return chisq

def chisq_SN(theta_sn, a_sn, y_sn, Icov):
    H0, O_m0, w, Mb = theta_sn
    return chi2_SN(a_sn, H0, O_m0, w, Mb, y_sn, Icov)

