# Bibliotecas:
import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import solve_ivp

# Parâmetros:
O_r0 = 0
mu = 10**(-7)
k = 0.125              # r = 8 Mpc/h
#n=1
ti = 0.17
tf = 1.0
p = 1000
t = np.linspace(ti, tf, p)
z = (1/t) - 1

# Modelo LCDM:
def fgRG(t, y, H0, O_m0):
    fg_RG  = y[0]

    O_m = O_m0*t**(-3)
    O_r = O_r0*t**(-4)
    O_L = 1 - O_m0

    H_RG = H0*np.sqrt(O_m + O_r + O_L)
    dH_RG = - (H_RG/t) - 0.5*(H0/t)*(H0/H_RG)*(O_m + 2*O_r - 2*O_L)

    faux1 = 3*H0**2
    faux2 = 2*(t**2)*(H_RG**2)

    dfg_RG = - ((dH_RG/H_RG) + ((2+fg_RG)/t))*fg_RG + (3/2)*((H0/H_RG)**2)*(O_m/t)
    return dfg_RG

def fgLsol(H0, O_m0):
  # Integração:
  t_span =[ti, tf]
  # Condições iniciais:
  Hi = H0*np.sqrt(O_m0*ti**(-3) + (1 - O_m0))
  O_mi = O_m0*ti**(-3)
  O_ri = O_r0*ti**(-4)
  O_L = 1 - O_m0
  fgi = ((H0/Hi)**2 * O_mi)**(6/11)
  y0 = [fgi]
  # Solução RG:
  solRG = solve_ivp(fgRG, t_span, y0, t_eval=t, method='LSODA', rtol = 10**(-6), args=(H0, O_m0))
  fg_RG = solRG.y[0]
  return fg_RG


