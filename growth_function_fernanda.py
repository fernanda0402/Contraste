# D(t) according to the Starobinsky model:
def growth_S(t, y, H0, O_m0, lbd, n):
  yH = y[0]
  YH = y[1]
  fg_S = y[2]

  O_m = O_m0*t**(-3)
  O_r = O_r0*t**(-4)
  chi = O_r0/O_m0
  ms = (H0**2)*O_m0
  O_L = 1 - O_m0
  R = 3*ms*(4*yH + t*YH + t**(-3))

  Rs = 6*(H0**2)*O_L/lbd
  star = 1 + (R/Rs)**2
  f = R + lbd*Rs*((star**(-n)) - 1)
  fR = 1 - 2*n*lbd*(R/Rs)*((star)**(-(n+1)))
  fRR = (2*n*lbd/Rs)*(2*(n+1)*((R/Rs)**2)*(star**(-n-2)) - (star**(-n-1)))

  yaux1 = yH + t**(-3) + chi*t**(-4)
  yaux2 = t**(-3) + 2*chi*t**(-4)
  j1 = 4 + (1/yaux1)*(1-fR)/(6*ms*fRR)
  j2 = (1/yaux1)*(2-fR)/(3*ms*fRR)
  j3 = - 3*t**(-3) - (((1-fR)*yaux2 + (R-f)/(3*ms))/yaux1)*(1/(6*ms*fRR))
  J1 = (1/t)*(1 + j1)
  J2 = (1/t)*(j2/t)
  J3 = (1/t)*(j3/t)

  dYH = - J1*YH - J2*yH - J3

  H_S = np.sqrt(ms*(yH + (1/t)**3 + chi*(1/t)**4))
  dH_S = (R/(6*t*H_S)) - (2*H_S/t)

  gaux3 = (fRR/fR)*(k/t)**2
  Geffn = (1/(fR))*(1 + 4*gaux3)/(1 + 3*gaux3)
  faux1 = 3*Geffn*H0**2
  faux2 = 2*t*H_S*H_S

  dfg_S = - ((dH_S/H_S) + ((2 + fg_S)/t))*fg_S + (faux1/faux2)*O_m

  return [YH, dYH, dfg_S]

def fg_S(H0, O_m0, lbd, n):
  # Integração:
  t_span =[ti, tf]

  # Condições iniciais:
  Hi = H0*np.sqrt(O_m0*ti**(-3) + (1 - O_m0))
  O_mi = O_m0*ti**(-3)
  O_ri = O_r0*ti**(-4)
  O_L = 1 - O_m0
  fgi = ((H0/Hi)**2 * O_mi)**(6/11)
  y0 = [(1-O_m0)/O_m0, 0, fgi]

  # Solução RG:
  sol_S = solve_ivp(growth_S, t_span, y0, t_eval=t, method='LSODA', rtol = 10**(-6), args=(H0, O_m0, lbd, n))
  fg_S = sol_S.y[2]
  return fg_S

