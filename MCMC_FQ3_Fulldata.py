# m_B(t) from GR/LCDM model:
def Int_GR(H0, O_m0):
  ms = H0*np.sqrt(O_m0)
  O_L = 1 - O_m0
  hyper = sp.special.hyp2f1
  O_m = O_m0*t**(-3)
  H_GR = H0*np.sqrt(O_m + O_L)

  x1 = - 1/(6*w)
  x2 = 1 + x1
  x3 = 1 - (1/O_m0)
  x4 = 1 - ((1/O_m)*(H_GR/H0)**2)

  IntGR = (2/ms)*(hyper(1/2,x1,x2,x3) - np.sqrt(t)*hyper(1/2,x1,x2,x4))
  return IntGR

def IntGR_interp(H0, O_m0):
  x_interp = df['acmb']
  y_interp = np.interp(x_interp, t, Int_GR(H0, O_m0))
