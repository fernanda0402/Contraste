# Modelo f(Q)3
def contrast_Q3(t, y, H0, O_m0, m):
    D_Q3 = y[0]
    dD_Q3 = y[1]

    O_m = O_m0*t**(-3)
    O_L = 1 - O_m0 - O_r0

    M = m*H0

    H_Q3 = H0*np.sqrt(O_m + O_L)
    dH_Q3 = -(3/2)*H0*(H0/H_Q3)*(O_m/t) # derivada de H com relação ao fator de escala

    Q = 6*(H_Q3)**2

    dfQ_3 = 1 + M*(Q**(-1/2)) / 2

    f1 = 3*(H0**2)*O_m
    f2 = 2*(t**2)*(H_Q3**2)*dfQ_3

    ddD_Q3 = - ((3/t) + (dH_Q3/H_Q3))*dD_Q3 + (f1/f2)*D_Q3  # equação do contraste
    return [dD_Q3, ddD_Q3]


def D_Q3(H0, O_m0, m):
    y0 = [ti, 1]
    sol_Q3 = solve_ivp(contrast_Q3, t_span, y0, t_eval=t, method='LSODA', args=(H0, O_m0, m))
    D_Q3 = sol_Q3.y[0]
    return D_Q3

def fs8_Q3(arsd, H0, O_m0, sig80, m):
    y0 = [0.2, 1]
    sol_Q3 = solve_ivp(contrast_Q3, t_span, y0, t_eval=arsd, method='LSODA', rtol = 10**(-6), args=(H0, O_m0, m))
    dD_Q3 = sol_Q3.y[1]
    fsig8_Q3 = sig80*sol_Q3.t*(dD_Q3/D_Q3(H0, O_m0, m)[999])
    return fsig8_Q3

