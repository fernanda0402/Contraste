# --------------- chi2 SNe --------------- #
def delta(a_sn, H0, O_m0, Mb, y_sn):
  mb_model = mag_GR(a_sn, H0, O_m0, Mb)
  delta = y_sn - mb_model
  return delta

def chi2_SN(a_sn, H0, O_m0, Mb, y_sn, Icov):
  chisq = np.sum(np.dot(np.dot(delta(a_sn, H0, O_m0, Mb, y_sn), Icov), delta(a_sn, H0, O_m0, Mb, y_sn)))
  return chisq

def chisq_SN(theta_sn, a_sn, y_sn, Icov):
    H0, O_m0, Mb = theta_sn
    return chi2_SN(a_sn, H0, O_m0, Mb, y_sn, Icov)

