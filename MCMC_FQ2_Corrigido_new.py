def Hubble_Q2t(t, H0, O_m0, m):
  O_m = O_m0 * t**(-3)
  M = m*H0
  M4 = M**4
  c0 = 3*(H0**2) #- M4/(4*(H0**2))
  H1 = c0*O_m
  H2 = H1**2 + 3*M4

  H_Q2 = np.sqrt((H1 + np.sqrt(H2))/6)
  return H_Q2

def Int1_Q2(H0, O_m0, m):
  y = 1/((t**2)*Hubble_Q2(t, H0, O_m0, m))
  IntQ2 = integrate.cumulative_trapezoid(y, t, initial=0)
  return IntQ2

def Int_Q2(H0, O_m0, m):
  y = 1/((t**2)*Hubble_Q2t(t, H0, O_m0, m))
  IntQ2 = Int1_Q2(H0, O_m0, m)[0] + integrate.cumulative_trapezoid(y, t, initial=0)
  return IntQ2

