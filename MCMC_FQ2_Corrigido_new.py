def contrast_Q2(t, y, H0, O_m0, m):
    D_Q2 = y[0]
    dD_Q2 = y[1]

    O_m = O_m0 * t**(-3)
    #O_r = O_r0 * t**(-4)
    #Omega = O_m + O_r

    M = m*H0
    M4 = M**4

    c0 = 3*(H0**2) #- M4/(4*(H0**2))
    H1 = c0*O_m
    H2 = H1**2 + 3*M4

    H_Q2 = np.sqrt((H1 + np.sqrt(H2))/6)

    HQ4 = H_Q2**4

    c1 = (M4/(12*HQ4)) + 1

    dH_Q2 = - (3/2)*(H0/t)*(H0/H_Q2)*(O_m/c1)

    Q = 6 * (H_Q2**2)
    dfQ_2 = 1 - (M4/(Q**2))

    f1 = 3 * H0**2 * O_m
    f2 = 2 * t**2 * H_Q2**2 * dfQ_2

    ddD_Q2 = - ((3/t) + dH_Q2/H_Q2)*dD_Q2 + ( (f1/f2)*D_Q2 )  # equação do contraste
    return [dD_Q2, ddD_Q2]

