def Hubble_Q2(acc, H0, O_m0, m):
  O_m = O_m0 * acc**(-3)
  M = m*H0
  M4 = M**4
  c0 = 3*(H0**2) #- M4/(4*(H0**2))
  H1 = c0*O_m
  H2 = H1**2 + 3*M4

  H_Q2 = np.sqrt((H1 + np.sqrt(H2))/6)
  return H_Q2

