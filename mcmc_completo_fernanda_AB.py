  O_ri = O_r0*ti**(-4)
  O_L = 1 - O_m0
  Ei = np.sqrt(O_mi + O_ri + O_L)
  dEi = - (Ei/ti) - ((O_mi + 2*O_ri - 2*O_L)/(2*ti*Ei))
  au1 = Ei/(ti**2)
  au2 = 0.5*(Ei + ti*dEi)/(ti*Ei)
  au3 = (O_mi + 2*O_ri - 2*O_L)/(ti*Ei)
  au4 = (3*O_mi + 8*O_ri)/Ei
  ddEi = au1 + au2*au3 + 0.5*(ti**(-2))*au4 - (dEi/ti)
  y0 = [Ei, dEi, ddEi, 0.2, 1]

  sol_AB = solve_ivp(contrast_AB, t_span, y0, t_eval=arsd, method='LSODA', rtol = 10**(-6), args=(O_m0, b))
  dD_AB = sol_AB.y[4]
  fs8_AB = sig80*sol_AB.t*(dD_AB/D_AB(O_m0, b)[999])
