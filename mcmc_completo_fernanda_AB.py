# H(t) para o modelo R2-AB:
def Hubble(t, y, H0, O_m0, b):
  H  =  y[0]
  dH  = y[1]
  ddH = y[2]

  O_m = O_m0*t**(-3)
  O_r = O_r0*t**(-4)

  R_vac = 12*H0**2
  e_AB = R_vac/np.log(1 + np.exp(2*b))
  M2 = e_AB/Delta

  R = 6*H*(2*H + t*dH)
  alpha = (R/e_AB) - b
  if abs(alpha) < 15:
    s = 1/np.cosh(alpha)
  else:
    s = 0

  A = H0*H0*(3*O_m + 4*O_r)
  B = t*H*dH*(np.tanh(alpha) + 1)
  C = 4*t*H*H*dH*(t*dH + 2*H)/M2
  if abs(alpha) < 15:
    D = ((6*t*t*H*H)/e_AB)*(((5*dH/t) + (dH*dH/H) +ddH)**2)*np.tanh(alpha)*s*s
    E = 6*(t**3)*(H**3)*((1/(3*M2)) + (0.5*s*s/e_AB))
  else:
    D = 0
    E = 6*(t**3)*(H**3)/(3*M2)

  F = (11*dH*dH/(t*H)) + (dH*dH*dH/(H*H)) + (6*ddH/t) + (4*dH*ddH/H)

  dddH = - ((A + B + C - D)/E) - F
  return [dH, ddH, dddH]

def solHCC(acc, H0, O_m0, b):
  t_span = [0.2, 1]
  ti = 0.2
  O_mi = O_m0*ti**(-3)
  O_ri = O_r0*ti**(-4)
  O_L = 1 - O_m0
  Hi = H0*np.sqrt(O_mi + O_ri + O_L)
  dHi = - ((H0*H0)/(2*ti*Hi))*(3*O_mi + 4*O_ri)
  ddHi = 0.5*(H0/(ti*Hi))**2*(Hi + ti*dHi)*(3*O_mi + 4*O_ri) + 0.5*(H0/(ti*Hi))**2*Hi*(9*O_mi + 16*O_ri)
  y0 = [Hi, dHi, ddHi]

  sol = solve_ivp(Hubble, t_span, y0, t_eval=acc, method='LSODA', rtol = 10**(-6), args=(H0, O_m0, b))
  H = sol.y[0]
  return H

